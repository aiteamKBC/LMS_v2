-- Stores staff-reviewed links for Teams participants that have no usable email.
-- Raw Teams attendance remains unchanged. Each link is scoped to one occurrence.
BEGIN;

CREATE TABLE IF NOT EXISTS curriculum.live_session_attendance_identity_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurrence_id varchar(128) NOT NULL,
    attendance_row_id varchar(128) NOT NULL,
    learner_profile_id bigint NOT NULL,
    canonical_email varchar(320) NOT NULL,
    display_name varchar(500) NOT NULL DEFAULT '',
    created_by varchar(320) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT curriculum_live_attendance_identity_link_uniq
        UNIQUE (occurrence_id, attendance_row_id),
    CONSTRAINT curriculum_live_attendance_identity_link_email_normalized
        CHECK (canonical_email = lower(btrim(canonical_email)) AND canonical_email <> '')
);

CREATE INDEX IF NOT EXISTS curriculum_live_attendance_identity_link_learner_idx
    ON curriculum.live_session_attendance_identity_links
       (learner_profile_id, occurrence_id);

COMMIT;

