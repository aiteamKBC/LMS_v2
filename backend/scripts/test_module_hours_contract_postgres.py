def prepare(directory, port):
    config = dict(host='127.0.0.1',port=port,user='postgres',dbname='postgres',connect_timeout=5)
    with psycopg.connect(**config,autocommit=True) as admin:
        host,actual_port,data,branch=admin.execute("SELECT host(inet_server_addr()),inet_server_port(),"
            "current_setting('data_directory'),current_setting('neon.branch_id',true)").fetchone()
        if (host!='127.0.0.1' or actual_port!=port or branch or
                Path(data).resolve()!=(directory/'pgdata').resolve() or directory.name!='module-hours-alignment-20261124'):
            raise RuntimeError('Not the selected disposable Module Hours cluster.')
        if any(not name.startswith('module_hours_test_') for name, in admin.execute(
                "SELECT datname FROM pg_database WHERE NOT datistemplate AND datname<>'postgres'")):
            raise RuntimeError('Unexpected non-test database in cluster.')
        config['dbname']='module_hours_test_'+uuid4().hex
        admin.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(config['dbname'])))
    schema=json.loads((directory/'schema.json').read_text())
    with psycopg.connect(**config) as conn:
        conn.execute('''CREATE SCHEMA curriculum; CREATE SCHEMA login; CREATE SCHEMA "Learner";
            CREATE TABLE login."Login_accounts"(id bigint PRIMARY KEY);
            CREATE TABLE curriculum.modules(module_catalogue_id text PRIMARY KEY);
            CREATE TABLE curriculum.source_lms_group_activities(group_id bigint,activity_id bigint,
                PRIMARY KEY(group_id,activity_id));
            CREATE TABLE "Learner".learner_progress_entries(id bigint PRIMARY KEY);
            CREATE TABLE "Learner".learner_journal_rows(id bigint PRIMARY KEY);
            INSERT INTO login."Login_accounts" VALUES(10),(20),(99);
            INSERT INTO curriculum.modules VALUES('M1'),('M2');
            INSERT INTO curriculum.source_lms_group_activities VALUES(1,11),(1,12),(2,21);
            INSERT INTO "Learner".learner_progress_entries VALUES(101);
            INSERT INTO "Learner".learner_journal_rows VALUES(201);''')
        order=('module_hours_access','module_hours_audit','module_hours_targets',
               'source_planned_hours_bulk_batches','source_planned_hours_bulk_items',
               'source_planned_hours_defaults','source_planned_hours_default_revisions')
        for name in order:
            fields=[]
            for col in schema[name]['columns']:
                default=col['default']; identity=col.get('identity')
                if default and default.startswith('nextval('):
                    conn.execute(sql.SQL('CREATE SEQUENCE {}').format(sql.SQL(re.search("'([^']+)'",default)[1])))
                suffix=(' GENERATED ALWAYS AS IDENTITY' if identity=='a' else
                        ' GENERATED BY DEFAULT AS IDENTITY') if identity else (' DEFAULT '+default if default else '')
                fields.append(sql.SQL('{} {}{}{}').format(sql.Identifier(col['name']),sql.SQL(col['type']),
                    sql.SQL(' NOT NULL' if col['required'] else ''),sql.SQL(suffix)))
            conn.execute(sql.SQL('CREATE TABLE curriculum.{} ({})').format(sql.Identifier(name),sql.SQL(',').join(fields)))
            for constraint in schema[name]['constraints']:
                conn.execute(sql.SQL('ALTER TABLE curriculum.{} ADD CONSTRAINT {} {}').format(
                    sql.Identifier(name),sql.Identifier(constraint['name']),sql.SQL(constraint['definition'])))
    return config


