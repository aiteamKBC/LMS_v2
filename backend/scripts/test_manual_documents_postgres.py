    def test_concurrent_mirror_operations(self):
        def worker(_):
            with psycopg.connect(**CONFIG,autocommit=True) as db:
                db.execute("SET statement_timeout='5s'")
                import time
                for attempt in range(20):
                    try:
                        # Each attempt reruns the whole transaction, including
                        # scope/ownership reads. The one-document assertion stays.
                        return self.create(db=db,mirrored=True)
                    except psycopg.errors.SerializationFailure:
                        if attempt == 19: raise
                        time.sleep(.01)
        with ThreadPoolExecutor(max_workers=2) as executor:
            results=list(executor.map(worker,range(2)))
        self.assertEqual(sum(r is not None for r in results),1)
        self.assertEqual(len(self.read()),1)

