def prepare(directory, port):
    config = dict(host='127.0.0.1', port=port, user='postgres', dbname='postgres', connect_timeout=5)
    with psycopg.connect(**config, autocommit=True) as admin:
        identity = admin.execute("SELECT host(inet_server_addr()), inet_server_port(), "
                                 "current_setting('data_directory'), current_setting('neon.branch_id',true)").fetchone()
        if (identity[0] != '127.0.0.1' or identity[1] != port or identity[3]
                or Path(identity[2]).resolve() != (directory / 'pgdata').resolve()
                or directory.name != 'backend-alignment-20261124'):
            raise RuntimeError('Not the approved disposable cluster.')
        if any(not row[0].startswith('alignment_test_') for row in admin.execute(
                "SELECT datname FROM pg_database WHERE NOT datistemplate AND datname<>'postgres'")):
            raise RuntimeError('Unexpected database in disposable cluster.')
        config['dbname'] = 'alignment_test_' + uuid4().hex
        admin.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(config['dbname'])))
    schema = json.loads((directory / 'schema.json').read_text())
    with psycopg.connect(**config) as conn:
        conn.execute('''CREATE SCHEMA curriculum; CREATE SCHEMA "Learner"; CREATE SCHEMA login;
            CREATE SCHEMA enrolment;
            CREATE TABLE curriculum.modules(module_catalogue_id varchar(128) PRIMARY KEY,title text,tutor_email text);
            CREATE TABLE curriculum.components(id varchar(128) PRIMARY KEY,module_catalogue_id varchar(128),type text,title text);
            CREATE TABLE "Learner".learners(id bigint PRIMARY KEY,enrolment_id bigint,coach_email text,learner_type text);
            CREATE TABLE login."Login_accounts"(id bigint PRIMARY KEY);
            CREATE TABLE enrolment."Created_users"(id bigint PRIMARY KEY);
            CREATE TABLE "Learner".learner_progress_entries(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                learner_id bigint,enrolment_id bigint,entry_order integer,kind text,module_ref text,module_title text,
                week_ref text,component_ref text,curriculum_component_ref text,component_title text,component_type text,
                expected_otjh numeric,actual_seconds integer,actual_basis text,reporting_started_at timestamptz,
                reporting_ended_at timestamptz,reporting_month text,reporting_timestamp_label text,source_system text,
                canonical_activity_key text,component_link_source text,component_link_status text,accepted boolean,
                deleted_at timestamptz,submitted_at timestamptz,passed boolean,feedback text,ssot_updated_at timestamptz,
                source_payload jsonb,feed_kind text,feed_action text,feed_title text,time_tracking_source text,
                time_tracking_session_ref text,time_tracking_calculation text,claimed_seconds integer,curriculum_component_fk text);
            INSERT INTO curriculum.modules VALUES ('M1','Synthetic module',''),('M2','Other module','');
            INSERT INTO curriculum.components VALUES ('C1','M1','reading','Synthetic'),('C2','M2','reading','Other');
            INSERT INTO "Learner".learners VALUES (1,91,'','apprenticeship'),(2,92,'','commercial');
            INSERT INTO login."Login_accounts" VALUES (7),(8);
            INSERT INTO enrolment."Created_users" VALUES (91),(92);''')
        order = ('activity_events','cache_epoch','cache_scope_epoch','record_revisions',
                 'record_versions','learner_activity_display_overrides','learner_activity_display_audit')
        for name in order:
            fields = []
            for column in schema[name]['columns']:
                default = column['default']
                identity = column.get('identity')
                if default and default.startswith('nextval('):
                    sequence = re.search("'([^']+)'", default)[1]
                    conn.execute(sql.SQL('CREATE SEQUENCE {}').format(sql.SQL(sequence)))
                fields.append(sql.SQL('{} {}{}{}').format(sql.Identifier(column['name']),
                    sql.SQL(column['type']), sql.SQL(' NOT NULL' if column['required'] else ''),
                    sql.SQL((' GENERATED ALWAYS AS IDENTITY' if identity == 'a' else
                             ' GENERATED BY DEFAULT AS IDENTITY') if identity else
                            (' DEFAULT ' + default if default else ''))))
            conn.execute(sql.SQL('CREATE TABLE curriculum.{} ({})').format(sql.Identifier(name),sql.SQL(',').join(fields)))
            for constraint in schema[name]['constraints']:
                conn.execute(sql.SQL('ALTER TABLE curriculum.{} ADD CONSTRAINT {} {}').format(
                    sql.Identifier(name),sql.Identifier(constraint['name']),sql.SQL(constraint['definition'])))
        conn.execute('INSERT INTO curriculum.cache_epoch VALUES (1,0)')
    return config


def configure(config):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    os.environ['DJANGO_SETTINGS_MODULE'] = 'config.settings_sqlite_test'
    from django.conf import settings
    db = dict(ENGINE='django.db.backends.postgresql',NAME=config['dbname'],USER='postgres',
              HOST=config['host'],PORT=config['port'],PASSWORD='',CONN_MAX_AGE=0,
              OPTIONS={'options': '-c statement_timeout=10000'})
    settings.DATABASES = {'default': dict(db), 'enrolment': dict(db)}
    settings.CACHES = {'default': {'BACKEND': 'django.core.cache.backends.locmem.LocMemCache'}}
    settings.EMAIL_BACKEND = 'django.core.mail.backends.locmem.EmailBackend'
    settings.CURRICULUM_ALLOW_RUNTIME_SCHEMA_BOOTSTRAP = False
    import django
    django.setup()


def suite(config):
    from django.db import connection, connections, transaction, IntegrityError, DatabaseError
    from django.test import RequestFactory, SimpleTestCase
    from curriculum_api import learner_activity_status as display, versioning, cache_scope, views, quality
    from old_otjh.service import ServiceError
    from system_audit import activity

    class ContractTests(unittest.TestCase):
        def setUp(self):
            with connection.cursor() as cursor:
                cursor.execute('TRUNCATE curriculum.record_versions, curriculum.record_revisions, '
                    'curriculum.learner_activity_display_audit, curriculum.learner_activity_display_overrides, '
                    'curriculum.activity_events, curriculum.cache_scope_epoch, "Learner".learner_progress_entries')
                cursor.execute('UPDATE curriculum.cache_epoch SET epoch=0 WHERE id=1')
            self.actor = SimpleNamespace(id=7,pk=7,email='synthetic@example.com',display_name='Synthetic')
            for item in (patch.object(views,'assigned_learners_for_scope',return_value=[{'id':1},{'id':2}]),
                         patch.object(display.curriculum_names,'attach',side_effect=lambda kind,rows:rows),
                         patch.object(display,'_accesses_of',return_value={'curriculum'}),
                         patch.object(views,'invalidate_curriculum_cache'),
                         patch.object(activity,'activity_available',return_value=True),
                         patch.object(activity,'workspace_column_available',return_value=True),
                         patch.object(activity,'actor_role',return_value='staff')):
                item.start(); self.addCleanup(item.stop)
            cache_scope.reset_state()

        def rows(self, statement, params=()):
            with connection.cursor() as cursor:
                cursor.execute(statement,params)
                return cursor.fetchall() if cursor.description else []

        def save(self, revision=0):
            return display.save(self.actor,'M1',1,'C1',{'displayStatus':'not_started',
                'expectedRevision':revision,'snapshotHash':display.digest([])})

        def reject(self, statement, params=()):
            with self.assertRaises(IntegrityError), transaction.atomic():
                self.rows(statement,params)

        def revision(self, kind='component', identity='C1', number=1):
            return self.rows('INSERT INTO curriculum.record_revisions '
                '(entity_type,entity_id,revision_no,action,snapshot) VALUES (%s,%s,%s,%s,%s) RETURNING id',
                [kind,identity,number,'created','{}'])[0][0]

        def pin(self, revision_id, kind='component', identity='C1', label='v1'):
            versioning.pin_versions(kind,[{'entity_id':identity,'version_label':label,'content_status':'draft'}],
                {(kind,identity):revision_id},{'email':'synthetic@example.com','name':'Synthetic'})

        def test_canonical_identity_and_compatible_enrolment_writes(self):
            self.assertEqual(self.save()['revision'],1)
            self.assertEqual(self.rows('SELECT learner_id,enrolment_id FROM curriculum.learner_activity_display_overrides'),[(1,91)])
            self.assertEqual(self.rows('SELECT learner_id,enrolment_id FROM curriculum.learner_activity_display_audit'),[(1,91)])

        def test_update_uses_canonical_enrolment_not_stored_override(self):
            self.save()
            self.rows('UPDATE curriculum.learner_activity_display_overrides SET enrolment_id=999')
            self.assertEqual(self.save(1)['revision'],2)
            self.assertEqual(self.rows('SELECT enrolment_id FROM curriculum.learner_activity_display_overrides'),[(91,)])

        def test_completed_override_keeps_time_entry_and_audit_atomic(self):
            from datetime import datetime, timezone
            start=datetime(2026,10,1,10,tzinfo=timezone.utc)
            end=datetime(2026,10,1,11,tzinfo=timezone.utc)
            # Date/month/holiday business rules are existing independent services;
            # exercise the real SQL writer and snapshots with their fixed result.
            with patch.object(display,'interval',return_value=(3600,start,end,'2026-10')), \
                 patch.object(display,'require_open_month'), \
                 patch('learner_api.working_hours_holidays.component_holiday_ranges',return_value=[]):
                result=display.save(self.actor,'M1',1,'C1',{'displayStatus':'completed',
                    'expectedRevision':0,'snapshotHash':display.digest([]),'durationSeconds':3600,
                    'startedAt':start.isoformat()})
            self.assertEqual(result['displayStatus'],'completed')
            self.assertEqual(result['actualOtjh'],1)
            snapshot=self.rows('SELECT after_snapshot FROM curriculum.learner_activity_display_audit')[0][0]
            snapshot=json.loads(snapshot) if isinstance(snapshot,str) else snapshot
            self.assertEqual(snapshot['progress'][0]['learner_id'],1)
            self.assertEqual(snapshot['progress'][0]['actual_seconds'],3600)
            self.assertEqual(snapshot['override']['display_status'],'completed')

        def test_invalid_references_and_component_module_mismatch(self):
            for actor,module,learner,component in [(self.actor,'M1',999,'C1'),(self.actor,'missing',1,'C1'),
                    (self.actor,'M1',1,'missing'),(self.actor,'M1',1,'C2'),
                    (SimpleNamespace(id=999,email='synthetic@example.com'),'M1',1,'C1')]:
                with self.subTest(module=module,learner=learner,component=component,actor=actor.id):
                    with self.assertRaises(ServiceError): display.resolve(actor,module,learner,component)

        def test_ownership_is_required(self):
            with patch.object(display,'_accesses_of',return_value={'coach'}):
                with self.assertRaises(ServiceError) as error: display.resolve(self.actor,'M1',1,'C1')
                self.assertEqual(error.exception.status,403)

        def test_read_identity_does_not_require_redundant_enrolment(self):
            with transaction.atomic():
                self.rows('UPDATE "Learner".learners SET enrolment_id=NULL WHERE id=1')
                self.assertEqual(display.resolve(self.actor,'M1',1,'C1')[0]['id'],1)
                with self.assertRaises(ServiceError): self.save()
                transaction.set_rollback(True)

        def test_before_after_snapshots_and_optimistic_locking(self):
            self.save(); self.save(1)
            before,after = self.rows('SELECT before_snapshot,after_snapshot FROM curriculum.learner_activity_display_audit WHERE revision=2')[0]
            before = json.loads(before) if isinstance(before,str) else before
            after = json.loads(after) if isinstance(after,str) else after
            self.assertEqual(before['override']['revision'],1)
            self.assertEqual(after['override']['revision'],2)
            self.assertEqual(before['progress'],after['progress'])
            with self.assertRaises(ServiceError) as error: self.save(1)
            self.assertEqual(error.exception.code,'record_changed')

        def test_audit_failure_rolls_back_override(self):
            original = display.query
            def fail(statement, params=()):
                if 'INSERT INTO "curriculum"."learner_activity_display_audit"' in statement:
                    raise DatabaseError('Synthetic failure')
                return original(statement,params)
            with patch.object(display,'query',side_effect=fail), self.assertRaises(DatabaseError): self.save()
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.learner_activity_display_overrides'),[(0,)])

        def test_stale_snapshot_is_rejected_without_writes(self):
            with self.assertRaises(ServiceError) as error:
                display.save(self.actor,'M1',1,'C1',{'displayStatus':'not_started',
                    'expectedRevision':0,'snapshotHash':'stale'})
            self.assertEqual(error.exception.code,'record_changed')
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.learner_activity_display_audit'),[(0,)])

        def test_commercial_identity_does_not_affect_another_learner(self):
            display.save(self.actor,'M1',2,'C1',{'displayStatus':'not_started',
                'expectedRevision':0,'snapshotHash':display.digest([])})
            self.assertEqual(self.rows('SELECT learner_id,enrolment_id FROM curriculum.learner_activity_display_overrides'),[(2,92)])

        def test_racing_foreign_key_failure_has_a_controlled_response(self):
            from inspect import unwrap
            request=RequestFactory().post('/activity/',data='{}',content_type='application/json')
            request.login_account=self.actor
            with patch.object(display,'save',side_effect=IntegrityError('private details')):
                response=unwrap(display.activity_status)(request,'M1',1,'C1')
            self.assertEqual(response.status_code,409)
            self.assertNotIn('private',response.content.decode())

        def test_concurrent_revision_compare_and_swap(self):
            def attempt(_):
                try:
                    self.save(); return 'saved'
                except ServiceError as error: return error.code
                finally: connections.close_all()
            with ThreadPoolExecutor(max_workers=2) as pool: results=list(pool.map(attempt,range(2)))
            self.assertCountEqual(results,['saved','record_changed'])
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.learner_activity_display_audit'),[(1,)])

        def test_all_display_foreign_keys_and_revision_checks(self):
            self.save()
            for table in display.TABLES:
                for column,value in [('learner_id',999),('actor_id',999),('module_id','missing'),('component_id','missing'),('revision',0)]:
                    with self.subTest(table=table,column=column):
                        self.reject(f'UPDATE curriculum.{table} SET {column}=%s',[value])

        def test_restrict_keeps_parents_and_audit(self):
            self.save()
            for relation,where in [('"Learner".learners','id=1'),('login."Login_accounts"','id=7'),
                    ('curriculum.modules',"module_catalogue_id='M1'"),('curriculum.components',"id='C1'")]:
                self.reject('DELETE FROM '+relation+' WHERE '+where)
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.learner_activity_display_audit'),[(1,)])

        def test_revision_version_identity_and_restrict(self):
            revision_id=self.revision(); self.pin(revision_id)
            self.reject('DELETE FROM curriculum.record_revisions WHERE id=%s',[revision_id])
            self.assertEqual(self.rows('SELECT revision_id FROM curriculum.record_versions'),[(revision_id,)])

        def test_import_restore_identity_collisions_are_controlled(self):
            for kind,identity in [('points_grant','C1'),('component','C2')]:
                revision_id=self.revision(kind,identity)
                with self.assertRaisesRegex(ValueError,'same entity'): self.pin(revision_id)
            with self.assertRaises(ValueError): self.pin(999999)
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.record_versions'),[(0,)])

        def test_database_rejects_mismatched_version_updates(self):
            revision_id=self.revision(); self.pin(revision_id)
            self.reject("UPDATE curriculum.record_versions SET entity_id='C2'")
            self.reject("UPDATE curriculum.record_versions SET entity_type='points_grant'")

        def test_revision_version_failure_is_atomic(self):
            with self.assertRaises(ValueError), transaction.atomic():
                revision_id=self.revision('points_grant')
                self.pin(revision_id)
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.record_revisions'),[(0,)])

        def test_same_identity_version_retry_is_idempotent(self):
            revision_id=self.revision(); self.pin(revision_id); self.pin(revision_id)
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.record_versions'),[(1,)])

        def record(self, event):
            request=RequestFactory().post('/activity/',data=json.dumps({'events':[{'kind':'page_view',
                'path':'/curriculum/modules',**event}]}),content_type='application/json')
            request.login_account=self.actor
            return activity.activity_record(request)

        def test_negative_durations_and_nonobject_details_are_rejected(self):
            for event in [{'durationMs':-1},{'durationMs':-0.5},{'durationMs':'-2'},
                          {'detail':[]},{'detail':None},{'detail':'text'}]:
                self.assertEqual(self.record(event).status_code,400)
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.activity_events'),[(0,)])

        def test_valid_events_and_missing_historical_accounts(self):
            response=self.record({'durationMs':0,'detail':{}})
            self.assertEqual(json.loads(response.content)['recorded'],1)
            self.rows("UPDATE curriculum.activity_events SET account_id=999999,occurred_at=recorded_at+interval '2 seconds'")
            self.assertEqual(activity.purge_expired_activity(),0)
            self.assertEqual(self.rows('SELECT account_id,occurred_at>recorded_at FROM curriculum.activity_events'),[(999999,True)])
            self.rows("UPDATE curriculum.activity_events SET occurred_at=recorded_at-interval '30 days'")
            activity.purge_expired_activity()
            self.assertEqual(self.rows('SELECT count(*) FROM curriculum.activity_events'),[(1,)])

        def test_activity_database_constraints(self):
            self.record({'detail':{}})
            self.reject('UPDATE curriculum.activity_events SET duration_ms=-1')
            self.reject("UPDATE curriculum.activity_events SET detail='[]'")

        def test_cache_contract(self):
            self.reject('INSERT INTO curriculum.cache_epoch VALUES (2,0)')
            self.reject('UPDATE curriculum.cache_epoch SET epoch=-1')
            self.reject("INSERT INTO curriculum.cache_scope_epoch VALUES (' ',1)")
            self.reject("INSERT INTO curriculum.cache_scope_epoch VALUES ('P1',-1)")
            with patch.object(cache_scope,'scope_table_available',return_value=True):
                for name in ['', ' ', '#bumps', '#global']:
                    with transaction.atomic(): cache_scope.bump_scopes([name])
            # Invalid attribution retains the existing global fallback without
            # ever attempting to store a blank or reserved programme key.
            self.assertEqual(dict(self.rows('SELECT scope,epoch FROM curriculum.cache_scope_epoch')),
                             {'#bumps':4,'*':4})

        def test_concurrent_cache_bumps_are_atomic_and_scoped(self):
            def bump(_):
                try:
                    with transaction.atomic():
                        self.rows('UPDATE curriculum.cache_epoch SET epoch=epoch+1 WHERE id=1')
                        cache_scope.bump_scopes({'P1'})
                finally: connections.close_all()
            with patch.object(cache_scope,'scope_table_available',return_value=True):
                with ThreadPoolExecutor(max_workers=4) as pool: list(pool.map(bump,range(12)))
                self.assertEqual(self.rows('SELECT epoch FROM curriculum.cache_epoch'),[(12,)])
                self.assertEqual(dict(self.rows('SELECT scope,epoch FROM curriculum.cache_scope_epoch')),{'#bumps':12,'P1':12})
                with transaction.atomic(): cache_scope.bump_scopes(None)
                self.assertEqual(dict(self.rows('SELECT scope,epoch FROM curriculum.cache_scope_epoch'))['*'],1)

        def test_curriculum_history_api_keeps_snapshot_opt_in(self):
            revision_id=self.revision(); self.pin(revision_id)
            with patch.object(versioning,'history_available',return_value=True):
                result=quality.curriculum_quality_record_history(RequestFactory().get('/history/'),'component','C1')
            body=json.loads(result.content)
            self.assertEqual(body['versions'][0]['revisionNo'],1)
            self.assertIsNone(body['snapshot'])

    result = unittest.defaultTestLoader.loadTestsFromTestCase(ContractTests)
    # Existing pure regression cases: no migrations, schema bootstraps, SQLite
    # fixtures, network transports or live service calls.
    modules = ['curriculum_api.test_cache_scope_no_db','curriculum_api.test_cache_latency_no_db',
        'curriculum_api.test_content_cache_no_db','curriculum_api.tests_change_log',
        'system_audit.tests_retention','system_audit.tests_pages','system_audit.tests_writes',
        'system_audit.tests_request_context','curriculum_api.tests_versioning','curriculum_api.tests',
        'curriculum_api.tests_learner_activity_status','coach_api.tests_errors','learner_api.tests']
    modules.append('learner_api.tests_account_deletion')
    selected = {'curriculum_api.tests': {'TeamsMultiDayRecurrenceTests','TeamsAttendanceRosterTests','CurriculumCacheTests'},
                'curriculum_api.tests_versioning': {'SnapshotShapeTests'},
                'curriculum_api.tests_learner_activity_status': {'ActivityScopeTests'},
                'learner_api.tests': {'TeamsAttendanceEligibilityTests','TeamsAttendanceSyncTests'}}
    for name in modules:
        module=importlib.import_module(name)
        for value in vars(module).values():
            if (isinstance(value,type) and value.__module__==name and issubclass(value,SimpleTestCase)
                    and value.__bases__ == (SimpleTestCase,)
                    and (name not in selected or value.__name__ in selected[name])):
                if value.__name__ == 'CurriculumCacheTests':
                    # This suite calls the real shared epoch writer. Permit it
                    # only here, after verification of the disposable database.
                    value.databases = {'default'}
                result.addTests(unittest.defaultTestLoader.loadTestsFromTestCase(value))
    return result


