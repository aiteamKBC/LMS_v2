"""Real PostgreSQL guard tests on the task's dedicated local, synthetic cluster only.

No Django startup, environment-file loading, production connections or live services.
Requires PostgreSQL 18 initialized under outputs/feedback-guard-20261027/cluster
and listening on 127.0.0.1:58347 as feedback_guard_test.
"""
import ast
import json
from pathlib import Path
import unittest

import psycopg
from psycopg import sql

ROOT = Path(__file__).resolve().parents[2]
CLUSTER = ROOT / 'outputs/feedback-guard-20261027/cluster'
DATABASE = 'feedback_guard_synthetic'
CONNECT = dict(host='127.0.0.1', port=58347, user='feedback_guard_test', connect_timeout=5)
migration = ROOT / 'backend/engagement_api/migrations/0007_feedback_lecture_creation_guard.py'
constants = {node.targets[0].id: ast.literal_eval(node.value) for node in ast.parse(migration.read_text()).body
             if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)}


def verify_cluster(connection):
    database, directory, role, address = connection.execute(
        "SELECT current_database(), current_setting('data_directory'), current_user, host(inet_server_addr())"
    ).fetchone()
    if (Path(directory).resolve() != CLUSTER.resolve() or role != 'feedback_guard_test'
            or address != '127.0.0.1' or database not in ('postgres', DATABASE)):
        raise RuntimeError('Refusing to write outside the dedicated synthetic local PostgreSQL cluster.')


class PostgreSQLCreationGuardTests(unittest.TestCase):
    def setUp(self):
        self.connection = psycopg.connect(**CONNECT, dbname=DATABASE)
        self.addCleanup(self.connection.close)
        self.addCleanup(self.connection.rollback)
        verify_cluster(self.connection)
        self.connection.execute('CREATE SCHEMA "Feedback"')
        self.connection.execute('''CREATE TABLE "Feedback".feedback_forms (
            id bigint PRIMARY KEY, form_type text NOT NULL, created_at timestamptz NOT NULL);
            CREATE TABLE "Feedback".feedback_deliveries (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                form_id bigint NOT NULL REFERENCES "Feedback".feedback_forms(id),
                occurrence_key text NOT NULL UNIQUE, starts_at timestamptz,
                available_at timestamptz, status text NOT NULL DEFAULT 'open');
            CREATE TABLE "Feedback".feedback_responses (
                id bigint PRIMARY KEY, delivery_id bigint REFERENCES "Feedback".feedback_deliveries(id), answer text);
            INSERT INTO "Feedback".feedback_forms VALUES
                (1,'post_lecture','2026-10-27 11:00:00+00'),
                (2,'general','2026-10-27 11:00:00+00'),
                (3,'post_lecture','2026-10-28 11:00:00+00');
            INSERT INTO "Feedback".feedback_deliveries (id,form_id,occurrence_key,starts_at)
                VALUES (99,1,'LEGACY','2026-10-06 08:00:00+00');
            INSERT INTO "Feedback".feedback_responses VALUES (1,99,'Historical answer');
        ''')
        self.connection.execute(constants['SQL'])

    def insert(self, key='NEW', starts='2026-10-27 11:00:00+00', form=1):
        return self.connection.execute('''INSERT INTO "Feedback".feedback_deliveries
            (form_id,occurrence_key,starts_at) VALUES (%s,%s,%s) RETURNING id''', (form, key, starts)).fetchone()[0]

    def rejected(self, operation):
        with self.assertRaises(psycopg.errors.CheckViolation) as caught:
            with self.connection.transaction():
                operation()
        self.assertEqual(caught.exception.diag.constraint_name, 'feedback_lecture_creation_guard')
        return caught.exception

    def test_direct_insert_before_boundary_and_missing_start_are_rejected(self):
        for starts in ('2026-10-06 11:00:00+00', '2026-10-27 10:59:59.999999+00', None):
            with self.subTest(starts=starts):
                self.rejected(lambda: self.insert(starts=starts))
        self.assertEqual(self.connection.execute('SELECT count(*) FROM "Feedback".feedback_deliveries').fetchone()[0], 1)

    def test_equal_and_future_instants_are_allowed_regardless_of_timezone(self):
        for index, starts in enumerate(('2026-10-27 11:00:00+00', '2026-10-27 14:00:00+03', '2026-11-01 11:00:00+00')):
            with self.subTest(starts=starts):
                self.assertIsInstance(self.insert(key=f'VALID-{index}', starts=starts), int)

    def test_other_feedback_types_keep_their_rules(self):
        for kind in ('general', 'post_event', 'event_rsvp', 'post_mcm_review', 'post_progress_review', 'mid_module', 'end_module'):
            self.connection.execute('UPDATE "Feedback".feedback_forms SET form_type=%s WHERE id=2', (kind,))
            self.insert(key=kind, starts='2026-01-01 00:00:00+00', form=2)
            self.insert(key=kind + '-NULL', starts=None, form=2)

    def test_update_cannot_move_valid_delivery_before_boundary_or_to_newer_form_version(self):
        delivery = self.insert()
        self.rejected(lambda: self.connection.execute('UPDATE "Feedback".feedback_deliveries SET starts_at=%s WHERE id=%s', ('2026-10-26 10:00:00+00', delivery)))
        self.rejected(lambda: self.connection.execute('UPDATE "Feedback".feedback_deliveries SET form_id=3 WHERE id=%s', (delivery,)))
        self.assertEqual(self.connection.execute('SELECT form_id FROM "Feedback".feedback_deliveries WHERE id=%s', (delivery,)).fetchone()[0], 1)

    def test_legacy_metadata_and_historical_answers_are_preserved(self):
        self.connection.execute('''UPDATE "Feedback".feedback_deliveries
            SET status='closed', form_id=form_id, starts_at=starts_at, occurrence_key=occurrence_key WHERE id=99''')
        self.rejected(lambda: self.connection.execute('UPDATE "Feedback".feedback_deliveries SET occurrence_key=\'REASSIGNED\' WHERE id=99'))
        self.assertEqual(self.connection.execute('SELECT answer FROM "Feedback".feedback_responses WHERE id=1').fetchone()[0], 'Historical answer')
        self.assertEqual(self.connection.execute('SELECT status FROM "Feedback".feedback_deliveries WHERE id=99').fetchone()[0], 'closed')

    def test_old_form_can_retain_valid_delivery_when_a_new_version_exists(self):
        delivery = self.insert(starts='2026-10-27 12:00:00+00')
        self.connection.execute('UPDATE "Feedback".feedback_deliveries SET form_id=1,starts_at=starts_at WHERE id=%s', (delivery,))
        self.assertEqual(self.connection.execute('SELECT form_id FROM "Feedback".feedback_deliveries WHERE id=%s', (delivery,)).fetchone()[0], 1)

    def test_rejected_occurrence_savepoint_does_not_abort_next_valid_occurrence(self):
        self.rejected(lambda: self.insert(key='OLD', starts='2026-10-06 10:00:00+00'))
        self.insert(key='VALID')
        self.assertEqual(self.connection.execute('SELECT occurrence_key FROM "Feedback".feedback_deliveries ORDER BY id').fetchall(), [('VALID',), ('LEGACY',)])

    def test_bulk_insert_has_no_partial_delivery_on_guard_failure(self):
        self.rejected(lambda: self.connection.execute('''INSERT INTO "Feedback".feedback_deliveries(form_id,occurrence_key,starts_at)
            VALUES (1,'BULK-VALID','2026-10-27 12:00:00+00'),(1,'BULK-OLD','2026-10-06 12:00:00+00')'''))
        self.assertEqual(self.connection.execute('SELECT count(*) FROM "Feedback".feedback_deliveries').fetchone()[0], 1)

    def test_unrelated_foreign_key_and_duplicate_errors_keep_their_identity(self):
        with self.assertRaises(psycopg.errors.ForeignKeyViolation), self.connection.transaction():
            self.insert(form=1000)
        self.insert()
        with self.assertRaises(psycopg.errors.UniqueViolation), self.connection.transaction():
            self.insert()

    def test_guard_reports_safe_context_and_context_rolls_back(self):
        before = self.connection.execute("SELECT current_setting('feedback.writer_context',true)").fetchone()[0]
        writer = json.dumps({'host': 'synthetic-host', 'pid': 123, 'code': 'test-code'})
        def attempt():
            self.connection.execute("SELECT set_config('feedback.writer_context',%s,true)", (writer,))
            self.insert(key='private@example.test', starts=None)
        error = self.rejected(attempt)
        detail = json.loads(error.diag.message_detail)
        self.assertEqual(detail['form_id'], 1)
        self.assertEqual(json.loads(detail['writer'])['host'], 'synthetic-host')
        self.assertNotIn('private@example.test', error.diag.message_detail)
        self.assertEqual(self.connection.execute("SELECT coalesce(nullif(current_setting('feedback.writer_context',true),''),'')").fetchone()[0], before or '')

    def test_install_is_repeatable_and_rollback_preserves_rows(self):
        self.connection.execute(constants['SQL'])
        self.assertEqual(self.connection.execute("SELECT count(*) FROM pg_trigger WHERE tgname='feedback_lecture_creation_guard'").fetchone()[0], 1)
        self.connection.execute(constants['REVERSE_SQL'])
        self.connection.execute(constants['REVERSE_SQL'])
        self.insert(starts='2026-10-06 10:00:00+00')
        self.assertEqual(self.connection.execute('SELECT answer FROM "Feedback".feedback_responses').fetchone()[0], 'Historical answer')


if __name__ == '__main__':
    with psycopg.connect(**CONNECT, dbname='postgres', autocommit=True) as admin:
        verify_cluster(admin)
        if not admin.execute('SELECT 1 FROM pg_database WHERE datname=%s', (DATABASE,)).fetchone():
            admin.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(DATABASE)))
    unittest.main(verbosity=2)
