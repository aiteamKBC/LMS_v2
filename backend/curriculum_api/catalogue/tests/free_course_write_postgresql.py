"""Canonical writer checks; provision only inside the isolated Phase 1F runner."""
import ast
import importlib
import os
from pathlib import Path

from django.db import connection, connections, transaction


def prepare_writer_fixture():
    """Extend the existing synthetic read fixture with real writer constraints."""
    assert os.environ.get('FREE_COURSE_AUTHORING_WRITE_POSTGRES_TESTS') == '1'
    assert [name for _, name in __import__('socket').if_nameindex()] == ['lo']
    assert len(Path('/proc/net/route').read_text().splitlines()) == 1
    assert not any(key in os.environ for key in ('NEW_ENDPOINT_URL', 'DATABASE_URL'))
    for alias in connections:
        settings = connections[alias].settings_dict
        assert settings['HOST'] == '127.0.0.1' and settings['NAME'] == 'phase1f'
    from .free_course_reads_postgresql import FreeCourseReadPostgreSQL
    FreeCourseReadPostgreSQL.setUpClass()
    FreeCourseReadPostgreSQL.tearDownClass()
    root = Path(__file__).resolve().parents[2]
    migration = ast.parse((root / 'migrations/0084_free_course_authoring_prerequisites.py').read_text())
    forward = next(ast.literal_eval(node.value) for node in migration.body
                   if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'FORWARD' for t in node.targets))
    # Exact existing ledger, constraints and indexes. Staff permissions are not
    # part of this fixture and no application migration runner is initialized.
    forward = forward[forward.index('CREATE TABLE curriculum.free_course_authoring_idempotency'):]
    with connection.cursor() as cursor:
        cursor.execute('TRUNCATE curriculum.free_programme_components, curriculum.free_course_weeks, '
                       'curriculum.free_courses, curriculum.quizzes, curriculum.quiz_course_links CASCADE')
        cursor.execute('ALTER TABLE curriculum.quizzes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY; '
                       'ALTER TABLE curriculum.quizzes ADD COLUMN title text; '
                       'ALTER TABLE curriculum.quiz_course_links ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY')
        cursor.execute(forward)
        cursor.execute('''CREATE TABLE "Learner".learner_free_courses (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, learner_id bigint,
            free_course_ref text REFERENCES curriculum.free_courses(id));
            CREATE TABLE "Learner".learner_free_course_progress (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, learner_id bigint,
            free_course_ref text REFERENCES curriculum.free_courses(id),
            component_ref text REFERENCES curriculum.free_programme_components(id), status text)''')
    soft_delete = importlib.import_module('curriculum_api.migrations.0089_free_course_content_soft_delete')
    with transaction.atomic(), connection.schema_editor() as editor:
        soft_delete.install(None, editor)
