"""Azure Blob storage for generated Progress Review PPTX files.

Same shape as enrolment_api.documents: these files are generated by the
platform from data already in the database, so — unlike learner-uploaded
evidence — there is nothing to scan and they go straight into their own
container via learner_api.evidence_storage.upload_blob, bypassing the
quarantine lifecycle entirely. Downloads always go out as short-lived SAS URLs,
so the container itself stays private.

Unlike the evidence containers (evidence-quarantine/approved/rejected) and
enrolment-docs, which every deployment provisions by hand up front,
AZURE_PROGRESS_REVIEW_CONTAINER is new and easy to forget to create — so this
module creates it itself on first use, the same "ensure, once per process"
shape as tables.ensure_progress_review_tables.
"""
from django.conf import settings

from learner_api.evidence_storage import azure_configured, blob_url, get_download_sas, upload_blob

PPTX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.presentationml.presentation"

_CONTAINER_READY = False


def storage_configured() -> bool:
    return azure_configured()


def _ensure_container():
    global _CONTAINER_READY
    if _CONTAINER_READY:
        return
    from azure.core.exceptions import ResourceExistsError
    from azure.storage.blob import BlobServiceClient

    client = BlobServiceClient(
        account_url=f"https://{settings.AZURE_STORAGE_ACCOUNT}.blob.core.windows.net",
        credential=settings.AZURE_STORAGE_KEY,
    )
    try:
        client.create_container(settings.AZURE_PROGRESS_REVIEW_CONTAINER)
    except ResourceExistsError:
        pass
    _CONTAINER_READY = True


def upload_pptx(file_obj, blob_name: str) -> str:
    """Upload the generated .pptx bytes and return its (unsigned) canonical URL."""
    container = settings.AZURE_PROGRESS_REVIEW_CONTAINER
    _ensure_container()
    upload_blob(file_obj, container, blob_name, PPTX_CONTENT_TYPE)
    return blob_url(container, blob_name)


def download_sas_for(container: str, blob_name: str, filename: str) -> str:
    return get_download_sas(container, blob_name, filename=filename)
